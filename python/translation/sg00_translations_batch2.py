def apply_text_translations(stage: str, translations: dict[str, str]) -> None:
    filepath = TRANSLATED_DIR / f"{stage}_STG.txt"
    lines = filepath.read_text(encoding="utf-8").splitlines()
    replaced = 0
    out_lines: list[str] = []
    for line in lines:
        m = DIALOGUE_RE.match(line)
        if m:
            prefix, text = m.group(1), m.group(2)
            if text in translations:
                out_lines.append(prefix + translations[text])
                replaced += 1
            else:
                out_lines.append(line)
        else:
            out_lines.append(line)
    filepath.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    print(f"  SG00 batch 2: {replaced} entries translated")


