def apply_text_translations(stage: str, translations: dict[str, str]) -> None:
    """Apply text-based translations to a stage file."""
    filepath = TRANSLATED_DIR / f"{stage}_STG.txt"
    if not filepath.exists():
        print(f"  ERROR: {filepath} not found")
        return

    lines = filepath.read_text(encoding="utf-8").splitlines()
    replaced = 0
    out_lines: list[str] = []

    for line in lines:
        m = DIALOGUE_RE.match(line)
        if m:
            prefix, text = m.group(1), m.group(2)
            if text in translations:
                out_lines.append(prefix + translations[text])
                replaced += 1
            else:
                out_lines.append(line)
        else:
            out_lines.append(line)

    filepath.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    print(f"  {stage}: {replaced} entries translated")


def main() -> int:
    if len(sys.argv) < 2:
        print("Usage: python apply_translations.py <STAGE> [STAGE...]")
        return 1

    stage_map = {
        "S200": S200_TRANSLATIONS,
        "S100": S100_TRANSLATIONS,
        "SG00": SG00_TRANSLATIONS,
    }

    for stage in sys.argv[1:]:
        stage = stage.upper()
        if stage not in stage_map:
            print(f"  ERROR: No translations for {stage}")
            continue
        print(f"Applying translations to {stage}...")
        apply_text_translations(stage, stage_map[stage])

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
