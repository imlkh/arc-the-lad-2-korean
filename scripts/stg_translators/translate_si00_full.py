def translate_line(line):
    """Translate a dialogue line while preserving formatting."""
    # Keep header, blank, and context lines as-is
    if (line.strip() == "" or
        line.startswith("Found ") or
        line.strip().startswith("---")):
        return line

    # Parse dialogue lines
    match = re.match(r'^(\s*0x[0-9A-F]+ \[0x[0-9A-F]+\] \[script:[0-9A-F]+ [0-9A-F]+\])(.*)$', line)
    if not match:
        return line

    prefix = match.group(1)
    japanese_text = match.group(2)

    # Apply translations
    korean_text = japanese_text
    for jp, kr in sorted(TRANSLATIONS.items(), key=lambda x: len(x[0]), reverse=True):
        korean_text = korean_text.replace(jp, kr)

    return prefix + korean_text

def main():
    input_file = os.path.join(BASE_DIR, "output", "decoded", "stg", "SI00_STG.txt.backup")
    output_file = os.path.join(BASE_DIR, "translated", "ko", "SI00_STG.txt")

    with open(input_file, 'r', encoding='utf-8') as f:
        lines = f.readlines()

    translated_lines = [translate_line(line) for line in lines]

    with open(output_file, 'w', encoding='utf-8') as f:
        f.writelines(translated_lines)

    print(f"Translation complete: {len(lines)} lines processed")
    print(f"Output written to: {output_file}")

if __name__ == "__main__":
    main()
