# The first 200 lines are already translated, so we start from line 200
with open(input_file, 'r', encoding='utf-8') as f:
    lines = f.readlines()

# Append remaining lines (200 onwards)
with open(output_file, 'a', encoding='utf-8') as f:
    for i, line in enumerate(lines[200:], start=200):
        # Check if line contains Japanese dialogue
        if '[script:' in line and ']' in line:
            # Extract parts
            parts = line.split(']', 2)
            if len(parts) >= 3:
                prefix = ']'.join(parts[:2]) + ']'
                japanese_text = parts[2]
                korean_text = translate_line(japanese_text)
                f.write(prefix + korean_text)
            else:
                f.write(line)
        else:
            # Keep headers, blank lines, context separators as-is
            f.write(line)

print(f"Translation complete! Output: {output_file}")
