# Read source
with open('translated/SC00_STG.txt', 'r', encoding='utf-8') as f:
    source_lines = f.readlines()

# Write complete translation
with open('translated/ko/SC00_STG.txt', 'w', encoding='utf-8') as out:
    for line in source_lines:
        line = line.rstrip()

        # Handle blank lines and context markers
        if not line or line.strip().startswith('---'):
            out.write(line + '\\n')
            continue

        # Handle dialogue lines
        if '0x' in line and '[script:' in line:
            parts = line.split(']', 2)
            if len(parts) >= 3:
                prefix = ']'.join(parts[:2]) + ']'
                text = parts[2]

                # Apply phrase translations first
                for jp, kr in translations.items():
                    text = text.replace(jp, kr)

                # Apply name translations
                for jp, kr in names.items():
                    text = text.replace(jp, kr)

                out.write(prefix + text + '\\n')
            else:
                out.write(line + '\\n')
        else:
            out.write(line + '\\n')

